//! Implements Hypridle configuration generation in crate `argvus control center power`. This separation keeps external effects from contaminating models, routes, or rendering.
//!
//! External tool dependencies remain in backend layers;
//! the UI consumes normalized models and results.
use argvus_control_center_core::paths::argvus_data_home;
use std::fs;
use std::path::PathBuf;
use std::sync::{Mutex, OnceLock, mpsc};
use std::time::Duration;

/// The ARGVUS hypridle configuration lives at the runtime path consumed by
/// `paths_config power/config/hypridle.conf` when ARGVUS_MUTABLE_CONFIG=1.
/// The modular power JSON is authoritative; this file is its derived output.
pub fn config_path() -> PathBuf {
  argvus_data_home().join("hypr/hypridle.conf")
}

/// Defines the constant `DEFAULT_HYPRIDLE_CONF`. Its explicit shape preserves the contract consumed by the rest of the workspace and keeps the intent visible as the module evolves.
const DEFAULT_HYPRIDLE_CONF: &str = r#"# ARGVUS hypridle configuration
# Generated by ARGVUS Control Center

general {
  lock_cmd = sh /usr/share/argvus/power/sh/hypr-power-menu.sh --lock
  before_sleep_cmd = sh /usr/share/argvus/power/sh/hypr-power-menu.sh --lock
  after_sleep_cmd = hyprctl dispatch 'hl.dsp.dpms({ action = "on" })'
}

listener {
  timeout = 300
  on-timeout = hyprctl dispatch 'hl.dsp.dpms({ action = "off" })'
  on-resume = hyprctl dispatch 'hl.dsp.dpms({ action = "on" })'
}
"#;

/// Returns the screen-off idle timeout in whole minutes.
pub fn screen_off_minutes() -> Option<u32> {
  let content = fs::read_to_string(config_path()).ok()?;
  listener_minutes_from(&content, calls_dpms_off)
}

/// Returns the screen-lock idle timeout in whole minutes.
pub fn lock_minutes() -> Option<u32> {
  let content = fs::read_to_string(config_path()).ok()?;
  listener_minutes_from(&content, calls_lock)
}

/// Updates the timeout of the listener whose `on-timeout` matches `matches`
/// and returns the new full configuration text. Errors when no such listener
/// exists, so we never guess at foreign layouts.
fn set_listener_minutes(
  content: &str,
  minutes: u32,
  matches: fn(&str) -> bool,
) -> Result<String, String> {
  let target = find_listener_timeout(content, matches).ok_or_else(|| {
    "O hypridle do ARGVUS não define um listener correspondente; nada foi alterado.".to_string()
  })?;
  let new_seconds = minutes.saturating_mul(60);
  let mut updated = String::with_capacity(content.len());
  for (index, line) in content.lines().enumerate() {
    if index == target {
      let indent: String = line
        .chars()
        .take_while(|character| character.is_whitespace())
        .collect();
      updated.push_str(&format!("{indent}timeout = {new_seconds}\n"));
    } else {
      updated.push_str(line);
      updated.push('\n');
    }
  }
  Ok(updated)
}

/// Updates the timeout of the DPMS-off listener and returns the new config text.
pub fn set_screen_off_minutes(content: &str, minutes: u32) -> Result<String, String> {
  set_listener_minutes(content, minutes, calls_dpms_off)
}

/// Updates the timeout of the screen-lock listener and returns the new config text.
pub fn set_lock_minutes(content: &str, minutes: u32) -> Result<String, String> {
  set_listener_minutes(content, minutes, calls_lock)
}

/// Builds a config by appending an active DPMS-off listener. Used when the
/// existing config has no recognizable screen-off listener (the stock ARGVUS
/// config ships with that example commented out), preserving everything else
/// such as the inactivity-lock listener.
fn with_screen_off_listener(content: &str, minutes: u32) -> String {
  let seconds = minutes.saturating_mul(60);
  let base = content.trim_end_matches(['\r', '\n']).to_string();
  format!(
    "{base}\n\nlistener {{\n  timeout = {seconds}\n  on-timeout = hyprctl dispatch 'hl.dsp.dpms({{ action = \"off\" }})'\n  on-resume = hyprctl dispatch 'hl.dsp.dpms({{ action = \"on\" }})'\n}}\n"
  )
}

/// Builds a config by appending an active screen-lock listener, reusing the
/// configured `general.lock_cmd` so a custom lock command survives the
/// "never" → value round trip.
fn with_lock_listener(content: &str, minutes: u32) -> String {
  let seconds = minutes.saturating_mul(60);
  let command = lock_command(content);
  let base = content.trim_end_matches(['\r', '\n']).to_string();
  format!("{base}\n\nlistener {{\n  timeout = {seconds}\n  on-timeout = {command}\n}}\n")
}

/// Removes the listener block whose `on-timeout` matches, disabling the related
/// auto action (the "never" option) while preserving every other listener.
#[cfg(test)]
fn remove_listener(content: &str, matches: fn(&str) -> bool) -> String {
  let pieces: Vec<&str> = content.split_inclusive('\n').collect();
  let mut drop = vec![false; pieces.len()];
  let mut in_listener = false;
  let mut matched = false;
  let mut start = 0;
  for (index, piece) in pieces.iter().enumerate() {
    let trimmed = piece.trim();
    if trimmed.is_empty() || trimmed.starts_with('#') {
      continue;
    }
    if !in_listener && trimmed.starts_with("listener") && trimmed.ends_with('{') {
      in_listener = true;
      matched = false;
      start = index;
      continue;
    }
    if in_listener {
      if trimmed.starts_with("on-timeout") && matches(trimmed) {
        matched = true;
      }
      if trimmed.ends_with('}') {
        if matched {
          for line in &mut drop[start..=index] {
            *line = true;
          }
        }
        in_listener = false;
      }
    }
  }
  pieces
    .into_iter()
    .zip(drop)
    .filter_map(|(piece, remove)| (!remove).then_some(piece))
    .collect()
}

/// Persists a power value into the modular canonical store before it is
/// persisted in the modular power file. The configuration service owns the
/// derived hypridle.conf projection and the targeted service restart.
fn persist_power_to_config(pointer: &str, minutes: u32) -> Result<(), String> {
  let status = argvus_control_center_core::process::command("argvus")
    .arg("config")
    .args(["set", pointer, &minutes.to_string()])
    .status()
    .map_err(|error| format!("failed to persist power timeout: {error}"))?;
  if !status.success() {
    return Err("argvus config rejected the power timeout".into());
  }
  Ok(())
}

/// Shared apply: persists a listener timeout (or disables it with `0`) and
/// requests a hypridle restart. Returns the previous value in minutes.
fn apply_listener_minutes(
  minutes: u32,
  matches: fn(&str) -> bool,
  setter: fn(&str, u32) -> Result<String, String>,
  listener_template: fn(&str, u32) -> String,
  canonical_pointer: &str,
) -> Result<u32, String> {
  // Keep the modular store authoritative. argvus-config.service projects the
  // value into the runtime hypridle.conf before the targeted restart worker
  // applies it.
  let path = config_path();
  let content = if path.exists() {
    fs::read_to_string(&path).map_err(|error| error.to_string())?
  } else {
    DEFAULT_HYPRIDLE_CONF.to_string()
  };
  let previous = listener_minutes_from(&content, matches).unwrap_or(0);
  let _ = (setter, listener_template);
  persist_power_to_config(canonical_pointer, minutes)?;
  restart_hypridle();

  Ok(previous)
}

const RESTART_DEBOUNCE: Duration = Duration::from_millis(800);

static RESTART_REQUEST: OnceLock<Mutex<Option<mpsc::Sender<()>>>> = OnceLock::new();

fn restart_hypridle() {
  let mut guard = RESTART_REQUEST
    .get_or_init(|| Mutex::new(None))
    .lock()
    .unwrap_or_else(std::sync::PoisonError::into_inner);
  let Some(sender) = guard.as_ref() else {
    let (sender, receiver) = mpsc::channel::<()>();
    *guard = Some(sender.clone());
    drop(guard);
    std::thread::Builder::new()
      .name("argvus-config-reload".to_string())
      .spawn(move || hypridle_restart_worker(receiver))
      .expect("failed to spawn argvus config reload worker");
    let _ = sender.send(());
    return;
  };
  let _ = sender.send(());
}

fn hypridle_restart_worker(receiver: mpsc::Receiver<()>) {
  loop {
    match receiver.recv_timeout(RESTART_DEBOUNCE) {
      Err(mpsc::RecvTimeoutError::Disconnected) => break,
      Err(mpsc::RecvTimeoutError::Timeout) => continue,
      Ok(()) => {
        while matches!(receiver.recv_timeout(RESTART_DEBOUNCE), Ok(())) {}
        let _ = argvus_control_center_core::config::reload_argvus_config_service();
      }
    }
  }
}

/// Writes a new DPMS timeout back to the ARGVUS hypridle config. Returns the
/// previous timeout when the change was applied.
pub fn apply_screen_off_minutes(minutes: u32) -> Result<u32, String> {
  apply_listener_minutes(
    minutes,
    calls_dpms_off,
    set_screen_off_minutes,
    with_screen_off_listener,
    "/power/screen_off_minutes",
  )
}

/// Writes a new screen-lock timeout back to the ARGVUS hypridle config. Returns
/// the previous timeout when the change was applied.
pub fn apply_lock_minutes(minutes: u32) -> Result<u32, String> {
  apply_listener_minutes(
    minutes,
    calls_lock,
    set_lock_minutes,
    with_lock_listener,
    "/power/lock_minutes",
  )
}

/// Extracts the timeout (in minutes) of the listener whose `on-timeout`
/// matches `matches`, reading `timeout = 0` as disabled.
fn listener_minutes_from(content: &str, matches: fn(&str) -> bool) -> Option<u32> {
  let target = find_listener_timeout(content, matches)?;
  content
    .lines()
    .enumerate()
    .filter(|(index, line)| {
      *index == target && line.trim_start().starts_with("timeout") && line.contains('=')
    })
    .map(|(_, line)| {
      line
        .split_once('=')
        .and_then(|(_, value)| value.trim().parse::<u32>().ok())
    })
    .next()
    .flatten()
    .and_then(|seconds| (seconds > 0).then(|| (seconds / 60).max(1)))
}

/// Locates the `timeout =` line that precedes the listener whose `on-timeout`
/// matches `matches`, which flags the listener this module manages.
fn find_listener_timeout(content: &str, matches: fn(&str) -> bool) -> Option<usize> {
  let mut current_timeout: Option<usize> = None;
  let mut target: Option<usize> = None;
  for (index, line) in content.lines().enumerate() {
    let trimmed = line.trim();
    if trimmed.starts_with('#') || trimmed.is_empty() {
      continue;
    }
    if trimmed.starts_with("timeout") && trimmed.contains('=') {
      current_timeout = Some(index);
    } else if trimmed.starts_with("on-timeout") && trimmed.contains('=') {
      let value = trimmed
        .split_once('=')
        .map(|(_, value)| value)
        .unwrap_or("");
      let value = value.trim();
      if matches(value) {
        target = current_timeout;
      }
      current_timeout = None;
    }
  }
  target
}

/// Executes the `calls_dpms_off` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn calls_dpms_off(value: &str) -> bool {
  let compact: String = value
    .chars()
    .filter(|character| !character.is_whitespace())
    .collect::<String>()
    .to_ascii_lowercase();
  compact.contains("dpmsoff")
    || compact.contains("dpms_state")
    || compact.contains("dpms,off")
    || compact.contains("hl.dsp.dpms({action=\"off\"")
}

/// Whether an `on-timeout` value is a screen-lock command.
fn calls_lock(value: &str) -> bool {
  let compact: String = value
    .chars()
    .filter(|character| !character.is_whitespace())
    .collect::<String>()
    .to_ascii_lowercase();
  compact.contains("lock")
}

/// The screen-lock command to reuse, taken from the config's `general.lock_cmd`
/// when available, with the ARGVUS default as a fallback.
fn lock_command(content: &str) -> String {
  content
    .lines()
    .find_map(|line| {
      let trimmed = line.trim();
      if trimmed.starts_with('#') {
        return None;
      }
      let (name, value) = trimmed.split_once('=')?;
      (name.trim() == "lock_cmd").then(|| value.trim().to_string())
    })
    .unwrap_or_else(|| "sh /usr/share/argvus/power/sh/hypr-power-menu.sh --lock".to_string())
}

