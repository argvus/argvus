//! Global window policy. Persistent preferences and compositor state are separate.
use crate::{ConfigDocument, ConfigError, ConfigResult, ConfigStore, hyprland_ipc};
use serde::{Deserialize, Serialize};
use std::fs::{self, OpenOptions};
use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt};
use std::path::{Path, PathBuf};
use std::process::ExitCode;

const POINTER: &str = "/hyprland/window_mode";

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum WindowMode {
  #[default]
  Tile,
  Floating,
}

impl WindowMode {
  pub fn as_str(self) -> &'static str {
    match self {
      Self::Tile => "tile",
      Self::Floating => "floating",
    }
  }

  pub fn parse(value: &str) -> ConfigResult<Self> {
    match value {
      "tile" => Ok(Self::Tile),
      "floating" => Ok(Self::Floating),
      _ => Err(ConfigError::Invalid(
        "window_mode must be tile or floating".into(),
      )),
    }
  }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Status {
  pub preferred: WindowMode,
  pub applied: Option<WindowMode>,
  pub available: bool,
  pub pending: bool,
  pub error: Option<String>,
}

pub fn from_document(document: &ConfigDocument) -> ConfigResult<WindowMode> {
  match document.get(POINTER) {
    None => Ok(WindowMode::Tile),
    Some(value) => value
      .as_str()
      .ok_or_else(|| ConfigError::Invalid("hyprland.window_mode must be a string".into()))
      .and_then(WindowMode::parse),
  }
}

/// Projection is shared by ordinary configuration generation and targeted changes.
pub fn project(document: &ConfigDocument, generated: &Path) -> ConfigResult<()> {
  if let Some(runtime) = runtime_root() {
    fs::DirBuilder::new()
      .recursive(true)
      .mode(0o700)
      .create(runtime)?;
  }
  crate::project::file_writes::atomic_write_lua(
    &generated.join("hypr/window-mode.lua"),
    &format!(
      "-- Generated by argvus config. Do not edit.\nreturn {{ mode = {:?} }}\n",
      from_document(document)?.as_str()
    ),
  )
}

fn runtime_root() -> Option<PathBuf> {
  std::env::var_os("XDG_RUNTIME_DIR")
    .map(PathBuf::from)
    .filter(|path| path.is_absolute())
    .map(|path| path.join("argvus"))
}

fn status_path() -> ConfigResult<Option<PathBuf>> {
  let Some(runtime) = runtime_root() else {
    return Ok(None);
  };
  let Ok(signature) = std::env::var("HYPRLAND_INSTANCE_SIGNATURE") else {
    return Ok(None);
  };
  hyprland_ipc::socket_path(&runtime, &signature)?;
  Ok(Some(
    runtime.join(format!("window-mode-{signature}.status")),
  ))
}

pub fn status() -> ConfigResult<Status> {
  let preferred = from_document(&ConfigStore::from_environment()?.load_effective()?)?;
  let mut status = Status {
    preferred,
    applied: None,
    available: false,
    pending: true,
    error: None,
  };
  let Some(path) = status_path()? else {
    return Ok(status);
  };
  match hyprland_ipc::eval(
    "assert(argvus_window_mode, 'ARGVUS window mode module is not loaded'); argvus_window_mode.write_status()",
  ) {
    Ok(_) => {
      status.available = true;
      let contents = fs::read_to_string(path)?;
      let mut lines = contents.lines();
      status.applied = lines.next().and_then(|mode| WindowMode::parse(mode).ok());
      status.error = lines
        .next()
        .filter(|line| !line.is_empty())
        .map(str::to_owned);
      status.pending = status.applied != Some(preferred) || status.error.is_some();
    }
    Err(error) => status.error = Some(error.to_string()),
  }
  Ok(status)
}

/// Serializes persistence, projection and IPC together across both interfaces.
pub fn set(mode: WindowMode) -> ConfigResult<Status> {
  let store = ConfigStore::from_environment()?;
  let root = store
    .path
    .parent()
    .ok_or(ConfigError::MissingConfigDirectory)?;
  fs::create_dir_all(root.join("data/internal"))?;
  let lock = OpenOptions::new()
    .create(true)
    .truncate(false)
    .read(true)
    .write(true)
    .mode(0o600)
    .open(root.join("data/internal/window-mode.lock"))?;
  crate::config_lock::lock_file(&lock)?;
  let _guard = crate::config_lock::LockGuard(&lock);
  // Restore before changing generated mode: its write may trigger a compositor reload.
  if mode == WindowMode::Tile {
    crate::windows::prepare_tile()?;
  }
  let document = store.update(POINTER, serde_json::json!(mode))?;
  let paths = crate::project::ArgvusPaths::from_store(&store)?;
  project(&document, &paths.generated)?;
  let application_error = if status_path()?.is_some() {
    hyprland_ipc::eval(&format!(
      "assert(argvus_window_mode, 'ARGVUS window mode module is not loaded'); argvus_window_mode.apply({:?})",
      mode.as_str()
    )).err().map(|error| error.to_string())
  } else {
    None
  };
  if mode == WindowMode::Floating
    && application_error.is_none()
    && crate::windows::runtime_path("sock").is_ok_and(|path| path.exists())
  {
    crate::windows::request("enable", None)?;
  }
  let mut status = status()?;
  if let Some(error) = application_error {
    eprintln!("argvus-config: window mode saved, application failed: {error}");
    status.error = Some(error);
    status.pending = true;
  }
  Ok(status)
}

pub fn run(args: &[String]) -> ExitCode {
  let result = (|| -> ConfigResult<()> {
    match args
      .iter()
      .map(String::as_str)
      .collect::<Vec<_>>()
      .as_slice()
    {
      ["get"] => println!(
        "{}",
        from_document(&ConfigStore::from_environment()?.load_effective()?)?.as_str()
      ),
      ["status", "--json"] => println!("{}", serde_json::to_string(&status()?)?),
      ["set", mode] => {
        let status = set(WindowMode::parse(mode)?)?;
        println!("{}", serde_json::to_string(&status)?);
        if status.error.is_some() {
          return Err(ConfigError::Invalid(
            "window mode saved but could not be applied".into(),
          ));
        }
      }
      _ => {
        return Err(ConfigError::Invalid(
          "usage: argvus config window-mode get|status --json|set tile|floating".into(),
        ));
      }
    }
    Ok(())
  })();
  match result {
    Ok(()) => ExitCode::SUCCESS,
    Err(error) => {
      eprintln!("argvus-config: {error}");
      ExitCode::FAILURE
    }
  }
}

#[cfg(test)]
mod tests {
  use super::*;

  #[test]
  fn missing_preference_defaults_to_tile_and_invalid_values_fail() {
    let mut document = ConfigDocument::default();
    assert_eq!(from_document(&document).unwrap(), WindowMode::Tile);
    document
      .set(POINTER, serde_json::json!("floating"))
      .unwrap();
    assert_eq!(from_document(&document).unwrap(), WindowMode::Floating);
    for value in [
      serde_json::json!("invalid"),
      serde_json::json!(true),
      serde_json::Value::Null,
    ] {
      assert!(document.set(POINTER, value).is_err());
      assert!(from_document(&document).is_err());
      assert!(document.validate().is_err());
    }
  }

  #[test]
  fn status_wire_format_preserves_pending_application() {
    let status = Status {
      preferred: WindowMode::Floating,
      applied: Some(WindowMode::Tile),
      available: true,
      pending: true,
      error: None,
    };
    let value = serde_json::to_value(&status).unwrap();
    assert_eq!(value["preferred"], "floating");
    assert_eq!(serde_json::from_value::<Status>(value).unwrap(), status);
  }
}

#[cfg(test)]
mod projection_tests {
  use super::*;

  #[test]
  fn preference_survives_store_round_trip_and_lua_projection() {
    let root = std::env::temp_dir()
      .join("argvus")
      .join(format!("window-mode-store-{}", std::process::id()));
    fs::create_dir_all(&root).unwrap();
    let store = ConfigStore::at(&root);
    for mode in [WindowMode::Floating, WindowMode::Tile, WindowMode::Tile] {
      let document = store.update(POINTER, serde_json::json!(mode)).unwrap();
      assert_eq!(from_document(&store.load().unwrap()).unwrap(), mode);
      project(&document, &root.join("generated")).unwrap();
      let lua = fs::read_to_string(root.join("generated/hypr/window-mode.lua")).unwrap();
      assert!(lua.contains(&format!("mode = {:?}", mode.as_str())));
    }
    assert!(store.update(POINTER, serde_json::json!("unknown")).is_err());
    assert_eq!(
      from_document(&store.load().unwrap()).unwrap(),
      WindowMode::Tile
    );
    fs::remove_dir_all(root).unwrap();
  }
}
