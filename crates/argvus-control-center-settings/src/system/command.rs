/// Executes the `run` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
pub fn run(args: &[String]) -> Result<(), String> {
  validate_args(args)?;
  ensure_root(args)?;
  match args {
    [area, action, value] if area == "timezone" && action == "set" => {
      run_command("timedatectl", &["set-timezone", value])
    }
    [area, action, value] if area == "hostname" && action == "set" => {
      host::validate_hostname(value)?;
      run_command("hostnamectl", &["set-hostname", value])
    }
    [area, action, value] if area == "datetime" && action == "ntp" => {
      run_command("timedatectl", &["set-ntp", value])
    }
    [area, action, value] if area == "datetime" && action == "set" => {
      run_command("timedatectl", &["set-time", value])
    }
    [area, action, value] if area == "locale" && action == "set-lang" => {
      run_command("localectl", &["set-locale", &format!("LANG={value}")])
    }
    [area, action, values @ ..] if area == "locale" && action == "set-generated" => {
      set_generated_locales(values)
    }
    [area, action, layout] if area == "keyboard" && action == "layout" => {
      run_command("localectl", &["set-x11-keymap", layout])
    }
    [area, action, layout, variant] if area == "keyboard" && action == "variant" => {
      run_command("localectl", &["set-x11-keymap", layout, "", variant])
    }
    [area, action, keymap] if area == "keyboard" && action == "console-keymap" => {
      run_command("localectl", &["set-keymap", keymap])
    }
    [area, action, unit] if area == "service" => {
      let args = service_args(action, unit)?;
      run_command(
        "systemctl",
        &args.iter().map(String::as_str).collect::<Vec<_>>(),
      )
    }
    [area, action, governor] if area == "governor" && action == "set" => set_governor(governor),
    [area, action, values @ ..] if area == "power" => run_power(action, values),
    [area, action, values @ ..] if area == "boot" => run_boot(action, values),
    [area, action, values @ ..] if area == "package" => run_package(action, values),
    [area, action, values @ ..] if area == "network" => run_network(action, values),
    [area, action, value] if area == "config" && action == "icons" => set_appearance_icons(value),
    _ => Err("unsupported system-settings command".to_string()),
  }
}

/// Executes the `run_network` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn run_network(action: &str, values: &[String]) -> Result<(), String> {
  match action {
    "dns" => {
      if values.len() != 3 {
        return Err("network dns requires 3 arguments".into());
      }
      match values[1].as_str() {
        "automatic" => restore_resolv_conf(&values[0]),
        "manual" => set_resolv_conf_manual(&values[0], &values[2]),
        _ => Err("mode must be automatic or manual".into()),
      }
    }
    _ => Err("unsupported network operation".into()),
  }
}

/// Applies the `set_appearance_icons` operation while preserving the persistence and local-update contract. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn set_appearance_icons(value: &str) -> Result<(), String> {
  let enabled = match value {
    "true" => true,
    "false" => false,
    _ => return Err("config icons value must be true or false".into()),
  };
  let mut config = AppConfig::load();
  config.set_icons(enabled)
}

/// Power actions are routed to systemd-logind. Lid/Power-key behaviors are
/// applied through an ARGVUS drop-in under `/etc/systemd/logind.conf.d` (the
/// upstream config file is never overwritten) and the running logind daemon is
/// asked to re-read its configuration with a SIGHUP.
fn run_power(action: &str, values: &[String]) -> Result<(), String> {
  match action {
    "set-lid" => {
      let (context, value) = split_lid(values)?;
      let key = lid_key(context)?;
      update_logind_drop_in(&[(key, value.to_string())])?;
      reload_logind()
    }
    "set-power-button" => {
      let [value] = values else {
        return Err("power button needs one value".into());
      };
      if !POWER_KEY_VALUES.contains(&value.as_str()) {
        return Err("unsupported HandlePowerKey value".into());
      }
      update_logind_drop_in(&[("HandlePowerKey", value.to_owned())])?;
      reload_logind()
    }
    "suspend-now" => run_command("systemctl", &["suspend"]),
    "hibernate-now" => run_command("systemctl", &["hibernate"]),
    _ => Err("unsupported power operation".into()),
  }
}

/// Executes the `validate_power` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn validate_power(action: &str, values: &[String]) -> Result<(), String> {
  match action {
    "set-lid" => {
      let (_, value) = split_lid(values)?;
      if valid_lid_value(value) {
        Ok(())
      } else {
        Err(format!("unsupported HandleLidSwitch value: {value}"))
      }
    }
    "set-power-button" => {
      if values.len() != 1 || !POWER_KEY_VALUES.contains(&values[0].as_str()) {
        Err("unsupported HandlePowerKey value".into())
      } else {
        Ok(())
      }
    }
    "suspend-now" | "hibernate-now" => {
      if values.is_empty() {
        Ok(())
      } else {
        Err("suspend-now and hibernate-now take no arguments".into())
      }
    }
    _ => Err("unsupported power operation".into()),
  }
}

/// Executes the `valid_lid_value` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn valid_lid_value(value: &str) -> bool {
  matches!(
    value,
    "ignore"
      | "poweroff"
      | "reboot"
      | "halt"
      | "kexec"
      | "suspend"
      | "hibernate"
      | "suspend-then-hibernate"
      | "lock"
      | "handled-by-system"
  )
}

/// Defines the constant `POWER_KEY_VALUES`. Its explicit shape preserves the contract consumed by the rest of the workspace and keeps the intent visible as the module evolves.
const POWER_KEY_VALUES: [&str; 7] = [
  "ignore", "poweroff", "reboot", "halt", "kexec", "suspend", "lock",
];

/// Executes the `split_lid` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn split_lid(values: &[String]) -> Result<(&str, &str), String> {
  match values {
    [value] => Ok(("default", value)),
    [context, value] => {
      if !["default", "battery", "ac", "docked"].contains(&context.as_str()) {
        return Err("lid context must be default, battery, ac or docked".into());
      }
      Ok((context, value))
    }
    _ => Err("set-lid expects [value] or [context, value]".into()),
  }
}

/// Executes the `lid_key` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn lid_key(context: &str) -> Result<&'static str, String> {
  match context {
    "default" => Ok("HandleLidSwitch"),
    "battery" => Ok("HandleLidSwitch"),
    "ac" => Ok("HandleLidSwitchExternalPower"),
    "docked" => Ok("HandleLidSwitchDocked"),
    _ => Err("unsupported lid context".into()),
  }
}

/// Defines the constant `LOGIND_DROP_IN`. Its explicit shape preserves the contract consumed by the rest of the workspace and keeps the intent visible as the module evolves.
const LOGIND_DROP_IN: &str = "/etc/systemd/logind.conf.d/argvus.conf";

/// Updates (or creates) the ARGVUS logind drop-in, replacing only the keys in
/// `entries` while preserving every other line and key already present.
fn update_logind_drop_in(entries: &[(&str, String)]) -> Result<(), String> {
  update_logind_drop_in_at(Path::new(LOGIND_DROP_IN), entries, true)
}

/// Applies the `update_logind_drop_in_at` operation while preserving the persistence and local-update contract. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn update_logind_drop_in_at(
  path: &Path,
  entries: &[(&str, String)],
  backup: bool,
) -> Result<(), String> {
  if fs::symlink_metadata(path)
    .map(|metadata| metadata.file_type().is_symlink())
    .unwrap_or(false)
  {
    return Err("refusing to update a symlinked logind drop-in".into());
  }
  let existing = fs::read_to_string(path).unwrap_or_default();
  let mut updated = String::new();
  let mut found: Vec<bool> = vec![false; entries.len()];
  for line in existing.lines() {
    let trimmed = line.trim_start();
    if !trimmed.starts_with('#') {
      let mut replaced = false;
      for (index, (key, _)) in entries.iter().enumerate() {
        if let Some(rest) = trimmed.strip_prefix(key)
          && rest.trim_start().starts_with('=')
        {
          updated.push_str(key);
          updated.push('=');
          updated.push_str(&entries[index].1);
          found[index] = true;
          replaced = true;
          break;
        }
      }
      if replaced {
        updated.push('\n');
        continue;
      }
      if trimmed.is_empty() && updated.ends_with('\n') {
        continue;
      }
    }
    updated.push_str(line);
    updated.push('\n');
  }
  for (index, (key, value)) in entries.iter().enumerate() {
    if !found[index] {
      if !updated.is_empty() && !updated.ends_with('\n') {
        updated.push('\n');
      }
      updated.push_str(key);
      updated.push('=');
      updated.push_str(value);
      updated.push('\n');
    }
  }
  let original = existing.trim_end();
  let written = updated.trim_end();
  if original != written {
    if backup && path.exists() {
      let _ = backup_file(path);
    }
    let metadata = fs::metadata(path)
      .or_else(|_| fs::metadata(Path::new("/etc/systemd/logind.conf")))
      .map_err(|error| error.to_string())?;
    let tmp = path.with_extension("tmp");
    {
      let mut file = fs::File::create(&tmp).map_err(|error| error.to_string())?;
      file
        .set_permissions(metadata.permissions())
        .map_err(|error| error.to_string())?;
      file
        .write_all((String::from(written) + "\n").as_bytes())
        .map_err(|error| error.to_string())?;
      file.sync_all().map_err(|error| error.to_string())?;
    }
    fs::rename(&tmp, path).map_err(|error| error.to_string())?;
  }
  Ok(())
}

/// Executes the `reload_logind` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn reload_logind() -> Result<(), String> {
  let _ = run_command("systemctl", &["kill", "-s", "HUP", "systemd-logind"]);
  Ok(())
}

/// Applies the `set_resolv_conf_manual` operation while preserving the persistence and local-update contract. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn set_resolv_conf_manual(connection: &str, dns_list: &str) -> Result<(), String> {
  let servers: Vec<&str> = dns_list
    .split(',')
    .map(str::trim)
    .filter(|value| !value.is_empty())
    .collect();
  if servers.is_empty() {
    return Err("no DNS servers provided".into());
  }
  for server in &servers {
    if !valid_ipv4(server) && !valid_ipv6(server) {
      return Err(format!("invalid DNS server: {server}"));
    }
  }
  let resolv = Path::new(RESOLV_CONF);
  if fs::symlink_metadata(resolv)
    .map(|metadata| metadata.file_type().is_symlink())
    .unwrap_or(false)
  {
    return Err(
      "/etc/resolv.conf is managed by a service (symlink); use automatic DNS mode".into(),
    );
  }
  backup_resolv_conf()?;
  write_resolv_conf(&resolv_conf_contents(&servers))?;
  run_command(
    "nmcli",
    &[
      "connection",
      "modify",
      connection,
      "ipv4.dns",
      dns_list,
      "ipv6.dns",
      dns_list,
      "ipv4.ignore-auto-dns",
      "yes",
      "ipv6.ignore-auto-dns",
      "yes",
    ],
  )
}

/// Executes the `restore_resolv_conf` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn restore_resolv_conf(connection: &str) -> Result<(), String> {
  let backup = Path::new(RESOLV_BACKUP);
  let restored = if backup.exists() {
    let contents = fs::read_to_string(backup).map_err(|error| error.to_string())?;
    write_resolv_conf(&contents)?;
    true
  } else {
    false
  };
  run_command(
    "nmcli",
    &[
      "connection",
      "modify",
      connection,
      "ipv4.dns",
      "",
      "ipv6.dns",
      "",
      "ipv4.ignore-auto-dns",
      "no",
      "ipv6.ignore-auto-dns",
      "no",
    ],
  )?;
  if restored {
    Ok(())
  } else {
    run_command("nmcli", &["connection", "up", connection])
  }
}

/// Executes the `backup_resolv_conf` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn backup_resolv_conf() -> Result<(), String> {
  let contents = fs::read_to_string(RESOLV_CONF).map_err(|error| error.to_string())?;
  if contents.contains(RESOLV_MARKER) || Path::new(RESOLV_BACKUP).exists() {
    return Ok(());
  }
  let mut file = fs::OpenOptions::new()
    .write(true)
    .create_new(true)
    .open(RESOLV_BACKUP)
    .map_err(|error| error.to_string())?;
  file
    .write_all(contents.as_bytes())
    .map_err(|error| error.to_string())?;
  file.sync_all().map_err(|error| error.to_string())
}

/// Applies the `write_resolv_conf` operation while preserving the persistence and local-update contract. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn write_resolv_conf(contents: &str) -> Result<(), String> {
  let path = Path::new(RESOLV_CONF);
  let tmp = path.with_extension("argvus-control-center.tmp");
  {
    let mut file = fs::File::create(&tmp).map_err(|error| error.to_string())?;
    file
      .set_permissions(fs::Permissions::from_mode(0o644))
      .map_err(|error| error.to_string())?;
    file
      .write_all(contents.as_bytes())
      .map_err(|error| error.to_string())?;
    file.sync_all().map_err(|error| error.to_string())?;
  }
  fs::rename(&tmp, path).map_err(|error| error.to_string())
}

/// Executes the `resolv_conf_contents` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn resolv_conf_contents(servers: &[&str]) -> String {
  let bodies = servers
    .iter()
    .map(|server| format!("nameserver {server}"))
    .collect::<Vec<_>>()
    .join("\n");
  format!("{RESOLV_MARKER}\n{bodies}\n")
}

