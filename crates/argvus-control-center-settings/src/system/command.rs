/// Applies the `set_governor` operation while preserving the persistence and local-update contract. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn set_governor(value: &str) -> Result<(), String> {
  if locate_command(&["powerprofilesctl"]).is_some() {
    let profile = match value {
      "performance" => Some("performance"),
      "powersave" | "power-saver" => Some("power-saver"),
      "balanced" => Some("balanced"),
      _ => None,
    };
    if let Some(profile) = profile
      && run_command("powerprofilesctl", &["set", profile]).is_ok()
    {
      return Ok(());
    }
  }
  let mut changed = 0;
  if let Ok(entries) = fs::read_dir("/sys/devices/system/cpu/cpufreq") {
    for entry in entries.flatten() {
      let path = entry.path();
      let available =
        fs::read_to_string(path.join("scaling_available_governors")).unwrap_or_default();
      if available
        .split_whitespace()
        .any(|candidate| candidate == value)
        && fs::write(path.join("scaling_governor"), format!("{value}\n")).is_ok()
      {
        changed += 1;
      }
    }
  }
  if let Ok(entries) = fs::read_dir("/sys/devices/system/cpu") {
    for entry in entries.flatten() {
      if !entry.file_name().to_string_lossy().starts_with("cpu") {
        continue;
      }
      let path = entry.path().join("cpufreq");
      let available =
        fs::read_to_string(path.join("scaling_available_governors")).unwrap_or_default();
      if available
        .split_whitespace()
        .any(|candidate| candidate == value)
        && fs::write(path.join("scaling_governor"), format!("{value}\n")).is_ok()
      {
        changed += 1;
      }
    }
  }
  (changed > 0)
    .then_some(())
    .ok_or_else(|| "no compatible cpufreq policy found".into())
}

/// Executes the `validate_boot` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn validate_boot(action: &str, values: &[String]) -> Result<(), String> {
  let token = |value: &str| {
    !value.is_empty()
      && value.len() <= 255
      && value
        .chars()
        .all(|character| character.is_ascii_alphanumeric() || matches!(character, '.' | '_' | '-'))
  };
  match action {
    "systemd-default" if values.len() == 1 => token(&values[0])
      .then_some(())
      .ok_or_else(|| "invalid systemd-boot entry".into()),
    "systemd-timeout" | "grub-timeout" if values.len() == 1 => values[0]
      .parse::<u32>()
      .ok()
      .filter(|value| *value <= 60)
      .map(|_| ())
      .ok_or_else(|| "timeout must be between 0 and 60".into()),
    "grub-cmdline" if values.len() == 1 => (!values[0].is_empty()
      && values[0].len() <= 2048
      && values[0]
        .chars()
        .all(|character| !character.is_control() && !matches!(character, '"' | '\\')))
    .then_some(())
    .ok_or_else(|| "invalid GRUB kernel command line".into()),
    "grub-regenerate" | "initramfs-regenerate" if values.is_empty() => Ok(()),
    "plymouth-theme" if values.len() == 1 => token(&values[0])
      .then_some(())
      .ok_or_else(|| "invalid Plymouth theme".into()),
    _ => Err("unsupported boot operation".into()),
  }
}

/// Executes the `run_boot` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn run_boot(action: &str, values: &[String]) -> Result<(), String> {
  match action {
    "systemd-default" => {
      let root = boot_root().ok_or("systemd-boot ESP was not found")?;
      let direct = root.join("loader/entries").join(&values[0]);
      let named = root
        .join("loader/entries")
        .join(format!("{}.conf", values[0]));
      if (!direct.is_file() || direct.is_symlink()) && (!named.is_file() || named.is_symlink()) {
        return Err("systemd-boot entry was not found".into());
      }
      stream_command(
        "bootctl",
        &[
          &format!("--esp-path={}", root.display()),
          "set-default",
          &values[0],
        ],
      )
    }
    "systemd-timeout" => {
      let root = boot_root().ok_or("systemd-boot ESP was not found")?;
      update_boot_key(&root.join("loader/loader.conf"), "timeout", &values[0])?;
      println!("ok");
      Ok(())
    }
    "grub-timeout" => {
      update_boot_key(Path::new("/etc/default/grub"), "GRUB_TIMEOUT", &values[0])?;
      println!("ok");
      Ok(())
    }
    "grub-cmdline" => {
      update_boot_key(
        Path::new("/etc/default/grub"),
        "GRUB_CMDLINE_LINUX_DEFAULT",
        &values[0],
      )?;
      println!("ok");
      Ok(())
    }
    "grub-regenerate" => {
      let config = ["/boot/grub/grub.cfg", "/boot/grub2/grub.cfg"]
        .iter()
        .map(Path::new)
        .find(|path| path.is_file())
        .ok_or("GRUB configuration path was not found")?;
      let tool = locate_command(&["grub-mkconfig", "grub2-mkconfig"])
        .ok_or("grub-mkconfig was not found")?;
      let config = config.to_string_lossy().into_owned();
      stream_command_path(&tool, &["-o", &config])
    }
    "initramfs-regenerate" => stream_command("mkinitcpio", &["-P"]),
    "plymouth-theme" => {
      let path = Path::new("/usr/share/plymouth/themes").join(&values[0]);
      if !path.is_dir() || path.is_symlink() {
        return Err("Plymouth theme was not found".into());
      }
      stream_command("plymouth-set-default-theme", &["-R", values[0].as_str()])
    }
    _ => Err("unsupported boot operation".into()),
  }
}

