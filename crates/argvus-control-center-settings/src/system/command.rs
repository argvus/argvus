/// Executes the `stream_command_display` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn stream_command_display(display: &str, command: &Path, args: &[&str]) -> Result<(), String> {
  let mut child = argvus_control_center_core::process::command(command)
    .args(args)
    .stdin(Stdio::null())
    .stdout(Stdio::piped())
    .stderr(Stdio::piped())
    .spawn()
    .map_err(|error| format!("{display}: {error}"))?;
  let stdout = child
    .stdout
    .take()
    .ok_or_else(|| format!("{display}: stdout was not captured"))?;
  let stderr = child
    .stderr
    .take()
    .ok_or_else(|| format!("{display}: stderr was not captured"))?;
  let stdout_forwarder = std::thread::spawn(move || forward_lines(BufReader::new(stdout)));
  let stderr_forwarder = std::thread::spawn(move || forward_lines(BufReader::new(stderr)));
  let status = child
    .wait()
    .map_err(|error| format!("{display}: {error}"))?;
  let stdout_lines = stdout_forwarder.join().unwrap_or_default();
  let stderr_lines = stderr_forwarder.join().unwrap_or_default();
  let any_output = !stdout_lines.is_empty() || !stderr_lines.is_empty();
  if status.success() {
    if !any_output {
      println!("ok");
    }
    Ok(())
  } else {
    let stderr = stderr_lines.concat().trim().to_string();
    Err(if stderr.is_empty() {
      format!("{display} exited with {status}")
    } else {
      stderr
    })
  }
}

/// Executes the `forward_lines` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn forward_lines(mut pipe: impl BufRead) -> Vec<String> {
  let mut lines = Vec::new();
  let mut line = String::new();
  loop {
    line.clear();
    match pipe.read_line(&mut line) {
      Ok(0) => break,
      Ok(_) => {
        let stdout = std::io::stdout();
        let mut handle = stdout.lock();
        let _ = handle.write_all(line.as_bytes());
        let _ = handle.flush();
        lines.push(std::mem::take(&mut line));
      }
      Err(_) => break,
    }
  }
  lines
}

/// Executes the `ensure_root` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn ensure_root(args: &[String]) -> Result<(), String> {
  if effective_uid() == 0 || std::env::var_os(ELEVATED_ENV).is_some() {
    return Ok(());
  }
  let pkexec = locate_pkexec().ok_or_else(|| "pkexec was not found; install polkit".to_string())?;
  let exe = std::env::current_exe().map_err(|error| error.to_string())?;
  let mut command = argvus_control_center_core::process::command(pkexec);
  command
    .arg(exe)
    .arg("system-settings")
    .args(args)
    .env_clear()
    .env(ELEVATED_ENV, "1");
  if let Some(value) = std::env::var_os("PATH") {
    command.env("PATH", value);
  } else {
    command.env(
      "PATH",
      "/usr/local/sbin:/usr/local/bin:/usr/bin:/usr/sbin:/sbin:/bin",
    );
  }
  if let Some(value) = std::env::var_os("DBUS_SESSION_BUS_ADDRESS") {
    command.env("DBUS_SESSION_BUS_ADDRESS", value);
  }
  if let Some(value) = std::env::var_os("DBUS_SYSTEM_BUS_ADDRESS") {
    command.env("DBUS_SYSTEM_BUS_ADDRESS", value);
  }
  if let Some(value) = std::env::var_os("XDG_RUNTIME_DIR") {
    command.env("XDG_RUNTIME_DIR", value);
  }
  let error = command.exec();
  Err(format!("failed to launch pkexec: {error}"))
}

/// Executes the `effective_uid` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
