/// Applies the `update_boot_key` operation while preserving the persistence and local-update contract. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn update_boot_key(path: &Path, key: &str, value: &str) -> Result<(), String> {
  if path.is_symlink() {
    return Err("refusing to update a symlinked boot configuration".into());
  }
  let contents = fs::read_to_string(path).map_err(|error| error.to_string())?;
  let mut found = false;
  let mut updated = String::new();
  for line in contents.lines() {
    let trimmed = line.trim_start();
    if !trimmed.starts_with('#') && trimmed.split_whitespace().next() == Some(key) {
      updated.push_str(key);
      updated.push(' ');
      updated.push_str(value);
      found = true;
    } else if key.starts_with("GRUB_")
      && !trimmed.starts_with('#')
      && trimmed.starts_with(&format!("{key}="))
    {
      updated.push_str(key);
      updated.push_str("=\"");
      updated.push_str(value);
      updated.push('"');
      found = true;
    } else {
      updated.push_str(line);
    }
    updated.push('\n');
  }
  if !found {
    if key.starts_with("GRUB_") {
      updated.push_str(&format!("{key}=\"{value}\"\n"));
    } else {
      updated.push_str(&format!("{key} {value}\n"));
    }
  }
  if updated != contents {
    backup_file(path)?;
    boot_write_atomic(path, &updated)?;
  }
  Ok(())
}

/// Executes the `backup_file` step in this module. The behavior is encapsulated here so callers depend on a clear domain decision instead of duplicating system or UI details.
fn backup_file(path: &Path) -> Result<PathBuf, String> {
  let stamp = SystemTime::now()
    .duration_since(UNIX_EPOCH)
    .unwrap_or_default()
    .as_secs();
  for suffix in 0..1000 {
    let backup = PathBuf::from(format!("{}.argvus-backup-{stamp}-{suffix}", path.display()));
    match fs::OpenOptions::new()
      .write(true)
      .create_new(true)
      .open(&backup)
    {
      Ok(mut file) => {
        file
          .write_all(&fs::read(path).map_err(|error| error.to_string())?)
          .map_err(|error| error.to_string())?;
        file.sync_all().map_err(|error| error.to_string())?;
        return Ok(backup);
      }
      Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => continue,
      Err(error) => return Err(error.to_string()),
    }
  }
  Err("could not create a unique boot backup".into())
}

